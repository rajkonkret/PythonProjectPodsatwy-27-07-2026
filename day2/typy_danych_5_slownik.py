# pusty słownik
dictionary = {}
print(dictionary)  # {}
print(type(dictionary))  # <class 'dict'>

dict_1 = dict()
print(dict_1)  # {}
print(type(dict_1))  # <class 'dict'>

# dodanie elementów do słonika
dictionary['imie'] = "Radek"
print(dictionary)  # {'imie': 'Radek'}

